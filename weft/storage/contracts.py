"""Persistence ports; implementations must enforce each mutation atomically."""

from pathlib import Path
from typing import Protocol

from weft.domain import AttemptRecord, RunRecord, RunState, Submission, TaskRecord, TaskSpec


class ConversationRepository(Protocol):
    # root remains a compatibility boundary for legacy JSONL exports.
    root: Path

    def load(self, thread_id: str) -> list[dict]: ...
    def load_context(self, thread_id: str) -> dict: ...
    def save(self, thread_id: str, messages: list[dict], context_state=None) -> None: ...


class ExecutionRepository(Protocol):
    def submit(self, thread_id: str, spec: TaskSpec, *, idempotency_key: str | None = None) -> Submission: ...
    def get_task(self, task_id: str) -> TaskRecord: ...
    def get_run(self, run_id: str) -> RunRecord: ...
    def rerun(self, task_id: str, previous_run_id: str) -> RunRecord: ...
    def attempts(self, run_id: str) -> list[AttemptRecord]: ...
    def start_attempt(self, run_id: str, expected_version: int, owner_id: str) -> tuple[RunRecord, AttemptRecord]: ...
    def transition(self, run_id: str, expected_version: int, target: RunState, *,
                   attempt_id: str | None = None, reason: str | None = None) -> RunRecord: ...
